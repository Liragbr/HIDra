#!/usr/bin/env bash
# gen_certs.sh — Generate self-signed CA + server TLS cert
# Run once before building the firmware and starting the server.
#
# Output files:
#   ca.key          CA private key        (keep secret, never ship)
#   ca.pem          CA certificate        (baked into firmware as ca_cert.h)
#   server.key      Server private key    (used by c2_server.py)
#   server.pem      Server certificate    (used by c2_server.py)
#   ca_cert.h       C header for firmware (copy into agent/ directory)
#
# Usage:
#   chmod +x gen_certs.sh
#   ./gen_certs.sh
#   cp ca_cert.h ../agent/
#
# Requirements: openssl >= 1.1.1

set -euo pipefail

# ── Configurable ──────────────────────────────────────────────────────
CA_SUBJ="/C=US/O=LabCA/CN=PicoC2-CA"
SRV_SUBJ="/C=US/O=LabSrv/CN=c2server"
DAYS_CA=3650     # 10 years for the CA
DAYS_SRV=825     # ~2 years for the server cert (browser limit, irrelevant here)
KEY_BITS=2048    # RSA key size; use 4096 for extra margin
SRV_IP="127.0.0.1"   # Add your real server IP here — used in SAN
SRV_DNS="localhost"   # And/or hostname

# ── 1. CA key + self-signed certificate ──────────────────────────────
echo "[1/4] Generating CA key…"
openssl genrsa -out ca.key "$KEY_BITS" 2>/dev/null

echo "[2/4] Generating CA certificate…"
openssl req -new -x509 \
    -key ca.key \
    -out ca.pem \
    -days "$DAYS_CA" \
    -subj "$CA_SUBJ" \
    -addext "basicConstraints=critical,CA:TRUE" \
    -addext "keyUsage=critical,keyCertSign,cRLSign"

# ── 2. Server key + CSR ───────────────────────────────────────────────
echo "[3/4] Generating server key + CSR…"
openssl genrsa -out server.key "$KEY_BITS" 2>/dev/null

openssl req -new \
    -key server.key \
    -out server.csr \
    -subj "$SRV_SUBJ"

# ── 3. Sign server cert with CA (TLS 1.3 requires SAN) ───────────────
echo "[4/4] Signing server certificate…"
cat > san.ext <<EOF
[req]
distinguished_name = req_distinguished_name
[req_distinguished_name]
[v3_req]
subjectAltName = IP:${SRV_IP}, DNS:${SRV_DNS}
keyUsage = critical, digitalSignature, keyEncipherment
extendedKeyUsage = serverAuth
basicConstraints = CA:FALSE
EOF

openssl x509 -req \
    -in server.csr \
    -CA ca.pem \
    -CAkey ca.key \
    -CAcreateserial \
    -out server.pem \
    -days "$DAYS_SRV" \
    -extfile san.ext \
    -extensions v3_req

rm -f server.csr san.ext ca.srl

# ── 4. Convert CA PEM → C header for firmware ────────────────────────
echo ""
echo "[*] Generating ca_cert.h for firmware…"

python3 - <<'PYEOF'
import re, sys

with open("ca.pem") as f:
    pem = f.read().strip()

# Escape the PEM string for embedding in C
escaped = pem.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n\"\n    \"")

header = f'''\
/**
 * ca_cert.h — CA certificate baked into Pico W firmware
 * Auto-generated by gen_certs.sh — do not edit by hand.
 * Regenerate whenever the CA cert is rotated.
 */

#ifndef CA_CERT_H
#define CA_CERT_H

/* PEM-encoded CA certificate (NUL-terminated).
 * mbedtls_x509_crt_parse() requires the +1 for the NUL. */
static const char ca_cert_pem[] =
    "{escaped}\\n";

#endif /* CA_CERT_H */
'''

with open("ca_cert.h", "w") as f:
    f.write(header)

print("  Written: ca_cert.h")
print("  Written: ca.pem")
print("  Written: server.pem")
print("  Written: server.key")
print("")
print("  Next steps:")
print("  1. cp ca_cert.h ../agent/")
print("  2. Edit agent/agent_config.h  (C2_HOST, RUNNER_TOKEN, …)")
print("  3. Build firmware:  cd agent/build && cmake .. && make")
print("  4. Start server:    RUNNER_TOKEN=… python3 server/c2_server.py")
PYEOF
